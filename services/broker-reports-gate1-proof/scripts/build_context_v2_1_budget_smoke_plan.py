def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail unless both committed artifacts match exact generated bytes.",
    )
    arguments = parser.parse_args(argv)
    safe_plan, transparent = build_artifacts()
    outputs = {
        SAFE_PLAN_PATH: _json_bytes(safe_plan),
        TRANSPARENT_PATH: _json_bytes(transparent),
    }
    write_or_check_outputs(outputs=outputs, check=arguments.check)
    print(
        json.dumps(
            {
                "status": "passed",
                "mode": "check" if arguments.check else "write",
                "provider_calls_total": 0,
                "safe_plan_file_sha256": _sha256_bytes(
                    outputs[SAFE_PLAN_PATH]
                ),
                "transparent_file_sha256": _sha256_bytes(
                    outputs[TRANSPARENT_PATH]
                ),
            },
            sort_keys=True,
        )
    )
    return 0


