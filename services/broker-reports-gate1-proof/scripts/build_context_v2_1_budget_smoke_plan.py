def write_or_check_outputs(
    *,
    outputs: dict[Path, bytes],
    check: bool,
) -> None:
    for path, expected in outputs.items():
        if check:
            actual = path.read_bytes() if path.is_file() else None
            if actual != expected:
                raise SystemExit(
                    f"context_v2_1_budget_smoke_precall_drift:{path.name}"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)


def _validate_projection(
    *,
    slot: Any,
    case: Any,
    provider_profile: Any,
    projection: Any,
    expected_answer: dict[str, Any],
    operation_identity: str,
) -> None:
    sealed_request = projection.sealed_request
    prepared_request = projection.prepared_request
    canonical_schema = (
        case.choice_contract.context_v2_1_response_profile
        .canonical_schema()
    )
    if (
        sha256_json(asdict(sealed_request))
        != slot.sealed_request_hash
        or sealed_request.sealed_request_receipt.integrity_hash
        != slot.sealed_request_receipt_integrity_hash
        or sealed_request.sealed_request_receipt.model_visible_request_hash
        != slot.model_visible_request_hash
        or sha256_json(canonical_schema) != slot.canonical_schema_hash
        or sha256_json(asdict(prepared_request))
        != slot.prepared_request_hash
        or sha256_json(prepared_request.provider_visible_schema)
        != slot.provider_visible_schema_hash
        or sha256_json(expected_answer) != slot.expected_answer_hash
        or not prepared_request.context_v2_1_budget_smoke_contract_is_bound(
            canonical_schema=canonical_schema,
            provider_profile=provider_profile,
            model_visible_request=sealed_request.model_visible_request,
            exact_model_id=slot.exact_model_id,
            operation_identity=operation_identity,
        )
    ):
        raise ValueError(
            "context_v2_1_budget_smoke_precall_projection_invalid"
        )


def _validate_artifacts(
    *,
    safe_plan: dict[str, Any],
    transparent: dict[str, Any],
) -> None:
    transparent_material = copy.deepcopy(transparent)
    supplied_integrity = transparent_material.pop(
        "integrity_sha256",
        None,
    )
    if (
        safe_plan.get("status") != "frozen_preflight_not_executed"
        or safe_plan.get("transport_executed") is not False
        or safe_plan.get("execution_accounting", {}).get(
            "provider_submissions_total"
        )
        != 0
        or transparent.get("status") != "preflight_not_executed"
        or transparent.get("transport_executed") is not False
        or transparent.get("slots_total")
        != BUDGET_SMOKE_MAXIMUM_PROVIDER_SUBMISSIONS
        or transparent.get("execution_accounting", {}).get(
            "provider_calls_total"
        )
        != 0
        or transparent.get("execution_accounting", {}).get(
            "provider_submissions_total"
        )
        != 0
        or supplied_integrity != sha256_json(transparent_material)
        or _recursive_keys(transparent) & _FORBIDDEN_ARTIFACT_KEYS
        or any(
            _ABSOLUTE_PATH_RE.search(value)
            for value in _recursive_strings(transparent)
        )
    ):
        raise ValueError(
            "context_v2_1_budget_smoke_precall_artifact_invalid"
        )


def _recursive_keys(value: Any) -> set[str]:
    if isinstance(value, dict):
        return {
            str(key)
            for key in value
        } | {
            nested
            for child in value.values()
            for nested in _recursive_keys(child)
        }
    if isinstance(value, (list, tuple)):
        return {
            nested
            for child in value
            for nested in _recursive_keys(child)
        }
    return set()


def _recursive_strings(value: Any) -> tuple[str, ...]:
    found: list[str] = []

    def visit(item: Any) -> None:
        if isinstance(item, str):
            found.append(item)
        elif isinstance(item, dict):
            for child in item.values():
                visit(child)
        elif isinstance(item, (list, tuple)):
            for child in item:
                visit(child)

    visit(value)
    return tuple(found)


def _read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"json_object_required:{path.name}")
    return value


def _json_bytes(value: dict[str, Any]) -> bytes:
    return (
        json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            indent=2,
            allow_nan=False,
        )
        + "\n"
    ).encode("utf-8")


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _sha256_text(value: str) -> str:
    return _sha256_bytes(value.encode("utf-8"))


